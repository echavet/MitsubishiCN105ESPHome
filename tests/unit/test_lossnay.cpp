/// Unit coverage for the Lossnay-specific protocol maps and captured fields.
#include <gtest/gtest.h>

#include "cn105_protocol.h"
#include "cn105_types.h"

#include <array>

using namespace cn105_protocol;

TEST(LossnayMaps, Modes) {
    EXPECT_STREQ(*lookup_value_opt(LOSSNAY_MODE_MAP, LOSSNAY_MODE, 3, 0x00), "HEAT");
    EXPECT_STREQ(*lookup_value_opt(LOSSNAY_MODE_MAP, LOSSNAY_MODE, 3, 0x01), "FAN");
    EXPECT_STREQ(*lookup_value_opt(LOSSNAY_MODE_MAP, LOSSNAY_MODE, 3, 0x02), "AUTO");
    EXPECT_EQ(lookup_index(LOSSNAY_MODE_MAP, 3, "HEAT"), 0);
    EXPECT_EQ(lookup_index(LOSSNAY_MODE_MAP, 3, "FAN"), 1);
    EXPECT_EQ(lookup_index(LOSSNAY_MODE_MAP, 3, "AUTO"), 2);
}

TEST(LossnayMaps, FanSpeeds) {
    constexpr std::array<const char*, 4> expected = {"1", "2", "3", "4"};
    for (int i = 0; i < 4; ++i) {
        EXPECT_STREQ(*lookup_value_opt(LOSSNAY_FAN_MAP, LOSSNAY_FAN, 4, static_cast<uint8_t>(i + 1)), expected[i]);
    }
    EXPECT_EQ(lookup_index(LOSSNAY_FAN_MAP, 4, "1"), 0);
    EXPECT_EQ(lookup_index(LOSSNAY_FAN_MAP, 4, "2"), 1);
    EXPECT_EQ(lookup_index(LOSSNAY_FAN_MAP, 4, "3"), 2);
    EXPECT_EQ(lookup_index(LOSSNAY_FAN_MAP, 4, "4"), 3);
}

TEST(LossnayMaps, UnsupportedValuesAreNotMapped) {
    EXPECT_FALSE(lookup_value_opt(LOSSNAY_MODE_MAP, LOSSNAY_MODE, 3, 0x03).has_value());
    EXPECT_FALSE(lookup_value_opt(LOSSNAY_FAN_MAP, LOSSNAY_FAN, 4, 0x00).has_value());
    EXPECT_EQ(lookup_index(LOSSNAY_MODE_MAP, 3, "COOL"), -1);
    EXPECT_EQ(lookup_index(LOSSNAY_FAN_MAP, 4, "AUTO"), -1);
}

TEST(LossnayMaps, ControlMasks) {
    EXPECT_EQ(LOSSNAY_POWER_MASK, 0x01);
    EXPECT_EQ(LOSSNAY_MODE_MASK, 0x04);
    EXPECT_EQ(LOSSNAY_FAN_MASK, 0x08);
}

TEST(LossnayFrames, ConnectProfileAndChecksum) {
    uint8_t packet[] = {0xFC, 0x5A, 0x01, LOSSNAY_PROFILE, 0x02, 0xCA, 0x01};
    EXPECT_EQ(checksum(packet, 7), 0xA4);
}

TEST(LossnayFrames, SettingsFieldPositions) {
    // 0x02 response: power=data[3], mode=data[5], fan=data[6].
    uint8_t heat_recovery[] = {0x02, 0x00, 0x00, 0x01, 0x00, 0x00, 0x04, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00};
    uint8_t bypass[] = {0x02, 0x00, 0x00, 0x01, 0x00, 0x01, 0x04, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00};
    uint8_t automatic[] = {0x02, 0x00, 0x00, 0x01, 0x00, 0x02, 0x04, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00};
    uint8_t off[] = {0x02, 0x00, 0x00, 0x00, 0x00, 0x01, 0x04, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00};

    const auto heat_recovery_fields = decode_lossnay_settings(heat_recovery);
    const auto bypass_fields = decode_lossnay_settings(bypass);
    const auto automatic_fields = decode_lossnay_settings(automatic);
    const auto off_fields = decode_lossnay_settings(off);

    EXPECT_STREQ(*lookup_value_opt(POWER_MAP, POWER, 2, heat_recovery_fields.power), "ON");
    EXPECT_STREQ(*lookup_value_opt(LOSSNAY_MODE_MAP, LOSSNAY_MODE, 3, heat_recovery_fields.mode), "HEAT");
    EXPECT_STREQ(*lookup_value_opt(LOSSNAY_MODE_MAP, LOSSNAY_MODE, 3, bypass_fields.mode), "FAN");
    EXPECT_STREQ(*lookup_value_opt(LOSSNAY_MODE_MAP, LOSSNAY_MODE, 3, automatic_fields.mode), "AUTO");
    EXPECT_STREQ(*lookup_value_opt(POWER_MAP, POWER, 2, off_fields.power), "OFF");
    EXPECT_STREQ(*lookup_value_opt(LOSSNAY_FAN_MAP, LOSSNAY_FAN, 4, heat_recovery_fields.fan), "4");
}

TEST(LossnayFrames, CapturedResponseChecksums) {
    uint8_t heat_recovery[] = {0xFC, 0x62, 0x01, 0x34, 0x10, 0x02, 0x00, 0x00, 0x01, 0x00, 0x00, 0x04, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00};
    uint8_t bypass[] = {0xFC, 0x62, 0x01, 0x34, 0x10, 0x02, 0x00, 0x00, 0x01, 0x00, 0x01, 0x04, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00};
    uint8_t automatic[] = {0xFC, 0x62, 0x01, 0x34, 0x10, 0x02, 0x00, 0x00, 0x01, 0x00, 0x02, 0x04, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00};
    uint8_t off[] = {0xFC, 0x62, 0x01, 0x34, 0x10, 0x02, 0x00, 0x00, 0x00, 0x00, 0x01, 0x04, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00};
    uint8_t actual_heat_recovery[] = {0xFC, 0x62, 0x01, 0x34, 0x10, 0x09, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x40, 0x00, 0x04, 0x04, 0x00, 0x00, 0x00, 0x00, 0x00};
    uint8_t actual_bypass[] = {0xFC, 0x62, 0x01, 0x34, 0x10, 0x09, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x40, 0x01, 0x04, 0x04, 0x00, 0x00, 0x00, 0x00, 0x00};

    EXPECT_EQ(checksum(heat_recovery, 21), 0x52);
    EXPECT_EQ(checksum(bypass, 21), 0x51);
    EXPECT_EQ(checksum(automatic, 21), 0x50);
    EXPECT_EQ(checksum(off, 21), 0x52);
    EXPECT_EQ(checksum(actual_heat_recovery, 21), 0x08);
    EXPECT_EQ(checksum(actual_bypass, 21), 0x07);
}

TEST(LossnayFrames, ActualAutomaticModeField) {
    // 0x09 response: data[7] is fixed 0x40; data[8] is actual mode;
    // data[9]/data[10] are fan repeats in these captures.
    uint8_t heat_recovery[] = {0x09, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x40, 0x00, 0x04, 0x04, 0x00, 0x00, 0x00, 0x00, 0x00};
    uint8_t bypass[] = {0x09, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x40, 0x01, 0x04, 0x04, 0x00, 0x00, 0x00, 0x00, 0x00};
    EXPECT_EQ(decode_lossnay_actual_mode(heat_recovery), 0x00);
    EXPECT_EQ(decode_lossnay_actual_mode(bypass), 0x01);
    EXPECT_EQ(heat_recovery[9], 0x04);
    EXPECT_EQ(bypass[9], 0x04);
    EXPECT_EQ(heat_recovery[10], 0x04);
    EXPECT_EQ(bypass[10], 0x04);
}

TEST(LossnayFrames, UnknownActualModeIsRejected) {
    uint8_t payload[] = {0x09, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x40, 0x02};
    EXPECT_FALSE(decode_lossnay_actual_mode(payload).has_value());
}

TEST(LossnayFrames, CapturedWriteChecksums) {
    uint8_t off[] = {0xFC, 0x41, 0x01, 0x34, 0x10, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00};
    uint8_t on_heat_recovery[] = {0xFC, 0x41, 0x01, 0x34, 0x10, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00};
    uint8_t mode_only_bypass[] = {0xFC, 0x41, 0x01, 0x34, 0x10, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00};
    uint8_t fan_only_4[] = {0xFC, 0x41, 0x01, 0x34, 0x10, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00};

    encode_lossnay_control(off, 0x00, std::nullopt, std::nullopt);
    encode_lossnay_control(on_heat_recovery, 0x01, 0x00, std::nullopt);
    encode_lossnay_control(mode_only_bypass, std::nullopt, 0x01, std::nullopt);
    encode_lossnay_control(fan_only_4, std::nullopt, std::nullopt, 0x04);

    EXPECT_EQ(checksum(off, 21), 0x78);
    EXPECT_EQ(checksum(on_heat_recovery, 21), 0x73);
    EXPECT_EQ(checksum(mode_only_bypass, 21), 0x74);
    EXPECT_EQ(checksum(fan_only_4, 21), 0x6D);
}

TEST(LossnayFrames, OperatingModeWriteAlwaysIncludesPowerOn) {
    uint8_t packet[21] = {0xFC, 0x41, 0x01, 0x34, 0x10, 0x01};
    encode_lossnay_control(packet, 0x01, 0x02, std::nullopt);

    EXPECT_EQ(packet[6], LOSSNAY_POWER_MASK | LOSSNAY_MODE_MASK);
    EXPECT_EQ(packet[8], 0x01);
    EXPECT_EQ(packet[10], 0x02);
}
